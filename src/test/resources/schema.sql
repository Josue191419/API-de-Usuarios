CREATE TABLE personas_josue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100),
    apellidos VARCHAR(150),
    correo VARCHAR(150),
    telefono VARCHAR(30)
);

CREATE TABLE roles_josue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100),
    descripcion VARCHAR(255)
);

CREATE TABLE usuarios_josue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(100) NOT NULL,
    estado VARCHAR(30) NOT NULL
);

CREATE TABLE persona_rol_josue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL,
    id_rol BIGINT NOT NULL,
    CONSTRAINT uq_persona_rol_josue UNIQUE (id_persona, id_rol),
    CONSTRAINT fk_persona_rol_persona_josue FOREIGN KEY (id_persona) REFERENCES personas_josue(id),
    CONSTRAINT fk_persona_rol_rol_josue FOREIGN KEY (id_rol) REFERENCES roles_josue(id)
);
